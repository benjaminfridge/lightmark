package com.benfridge.lightmark.data

import androidx.room.ColumnInfo
import androidx.room.Dao
import androidx.room.Database
import androidx.room.Entity
import androidx.room.Index
import androidx.room.Insert
import androidx.room.PrimaryKey
import androidx.room.Query
import androidx.room.RoomDatabase

/**
 * A highlighted range, in the coordinate space of `Document.plainText`.
 *
 * Storing character offsets rather than block indices means a highlight survives
 * re-parsing and reflow.
 */
@Entity(
    tableName = "highlights",
    indices = [Index("documentId")],
)
data class Highlight(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val documentId: String,
    val start: Int,
    val end: Int,
    val createdAt: Long,
    /**
     * The highlighted words, copied in at insert time.
     *
     * Denormalised on purpose. [start] and [end] locate the highlight for rendering, but
     * they only mean anything against the exact source text they were taken from: edit
     * the file afterwards and every offset in it drifts, silently. Storing the words
     * makes an export independent of the source files, and able to survive one being
     * edited, regenerated by a converter, or deleted.
     */
    @ColumnInfo(defaultValue = "") val text: String = "",
)

@Dao
interface HighlightDao {

    @Query("SELECT * FROM highlights WHERE documentId = :documentId ORDER BY start ASC")
    suspend fun list(documentId: String): List<Highlight>

    /** Every highlight, grouped by document and in reading order. For export. */
    @Query("SELECT * FROM highlights ORDER BY documentId ASC, start ASC")
    suspend fun listAll(): List<Highlight>

    @Query("SELECT COUNT(*) FROM highlights")
    suspend fun totalCount(): Int

    @Insert
    suspend fun insert(highlight: Highlight): Long

    @Query("DELETE FROM highlights WHERE id = :id")
    suspend fun delete(id: Long)
}

/**
 * Version 1. Note that the SDK's `buildDatabase` gives no way to pass migrations or a
 * destructive fallback (light-sdk issue #227), so any schema change here needs a
 * matching plan before release. Keep this stable.
 */
/**
 * What committing a new range does to the ranges already stored.
 *
 * Pure, so the arithmetic that decides whether two highlights become one is testable
 * without Room. Ranges that merely touch are absorbed as well as ones that overlap,
 * which is what joins a highlight continued onto the next page.
 */
data class HighlightMerge(
    val start: Int,
    val end: Int,
    val absorbedIds: List<Long>,
)

fun planMerge(existing: List<Highlight>, start: Int, end: Int): HighlightMerge {
    val touching = existing.filter { it.start <= end && it.end >= start }
    return HighlightMerge(
        start = (touching.map { it.start } + start).min(),
        end = (touching.map { it.end } + end).max(),
        absorbedIds = touching.map { it.id },
    )
}

@Database(entities = [Highlight::class], version = 1, exportSchema = true)
abstract class LightmarkDatabase : RoomDatabase() {
    abstract fun highlights(): HighlightDao
}
